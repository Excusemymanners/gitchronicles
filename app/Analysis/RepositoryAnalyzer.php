<?php

namespace App\Analysis;

use App\Exceptions\RepositoryProcessingException;
use App\Models\CodeSymbol;
use App\Models\FileImport;
use App\Models\Module;
use App\Models\ModuleDependency;
use App\Models\Repository;
use App\Models\RepositoryFile;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Process\Exceptions\ProcessTimedOutException;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Process;
use Illuminate\Support\Str;

/**
 * The code analysis of a cloned repository (Faza 5), in three steps:
 *
 * 1. listFiles(): `git ls-files` lists the files git tracks (so .gitignore is respected), and
 *    shouldAnalyze() leaves out libraries (vendor/, node_modules/), build output (dist/, build/),
 *    minified files, lock files, binary files and files over 1 MB;
 * 2. runAnalyzer(): analyzer/analyze.py (Python + tree-sitter) reads those files and answers,
 *    in JSON, with each file's language, lines, symbols and imports;
 * 3. save(): in one database transaction, the previous analysis of the repository is replaced
 *    by the new one: files, symbols, imports (with the file each one points to), modules
 *    (ModuleGrouper) and the dependencies between modules; the repository gets analyzed_at
 *    and a short description from its README.
 *
 * When the analyzer cannot run, the user sees a short Romanian message and the log gets the details.
 */
final class RepositoryAnalyzer
{
    /**
     * After this many seconds the analyzer is stopped.
     */
    public const TIMEOUT_SECONDS = 240;

    /**
     * Bigger files are not code someone wrote by hand (data, generated files), so they are skipped.
     */
    public const MAX_FILE_BYTES = 1024 * 1024;

    /**
     * Folders with code that is not the project's own: libraries and build output.
     */
    private const SKIPPED_FOLDERS = ['vendor', 'node_modules', 'dist', 'build'];

    /**
     * Minified files: generated, on one very long line.
     */
    private const SKIPPED_SUFFIXES = ['.min.js', '.min.css'];

    /**
     * Lock files: generated by the package managers, thousands of lines that would hide the real code.
     */
    private const LOCK_FILES = ['composer.lock', 'package-lock.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lock'];

    /**
     * How many rows one INSERT saves.
     */
    private const INSERT_CHUNK_SIZE = 500;

    /**
     * Analyze the repository's clone and save the result.
     *
     * @return array{files_total: int, files_analyzed: int, modules_total: int}
     */
    public function analyze(Repository $repository): array
    {
        $trackedFiles = $this->listFiles($repository);
        $filesToAnalyze = array_values(array_filter($trackedFiles, $this->shouldAnalyze(...)));

        $analysis = $this->runAnalyzer($repository, array_column($filesToAnalyze, 'path'));

        $modulesTotal = DB::transaction(fn (): int => $this->save($repository, $filesToAnalyze, $analysis['files']));

        return [
            'files_total' => count($trackedFiles),
            'files_analyzed' => count($analysis['files']),
            'modules_total' => $modulesTotal,
        ];
    }

    /**
     * Every file git tracks, with what git knows about it. One `git ls-files` call gives, for each file:
     * its mode (100644 = a normal file, 120000 = a symbolic link, 160000 = a submodule), the id
     * of its content (blob_sha), its size, and "-text" when git considers it binary.
     * With -z every record ends with "\0", so the piece after the last one is empty and skipped.
     *
     * @return list<array{path: string, mode: string, blob_sha: string, size_bytes: int, is_binary: bool}>
     */
    private function listFiles(Repository $repository): array
    {
        $output = Process::path($repository->clonePath())
            ->run(['git', 'ls-files', '-z', '--format=%(objectmode) %(objectname) %(objectsize) %(eolinfo:index) %(path)'])
            ->throw()
            ->output();

        $files = [];

        foreach (explode("\0", $output) as $record) {
            $fields = explode(' ', $record, 5);

            if (count($fields) < 5) {
                continue;
            }

            [$mode, $blobSha, $size, $lineEndings, $path] = $fields;

            $files[] = [
                'path' => $path,
                'mode' => $mode,
                'blob_sha' => $blobSha,
                'size_bytes' => (int) $size,
                'is_binary' => $lineEndings === '-text',
            ];
        }

        return $files;
    }

    /**
     * Whether a tracked file is the project's own text: a normal file (never a symbolic link,
     * which could point outside the clone), not binary, at most 1 MB, and not a library,
     * build output, minified or lock file. The path must also fit in the database and in the
     * analyzer's file list (one path per line).
     *
     * @param  array{path: string, mode: string, blob_sha: string, size_bytes: int, is_binary: bool}  $file
     */
    private function shouldAnalyze(array $file): bool
    {
        $folders = array_slice(explode('/', $file['path']), 0, -1);

        return in_array($file['mode'], ['100644', '100755'], true)
            && ! $file['is_binary']
            && $file['size_bytes'] <= self::MAX_FILE_BYTES
            && array_intersect($folders, self::SKIPPED_FOLDERS) === []
            && ! Str::endsWith($file['path'], self::SKIPPED_SUFFIXES)
            && ! in_array(basename($file['path']), self::LOCK_FILES, true)
            && strlen($file['path']) <= 1024
            && ! str_contains($file['path'], "\n");
    }

    /**
     * Run analyzer/analyze.py on the clone and return its JSON answer.
     *
     * The command is an array (no shell), the file list goes through stdin ("--files-from -"),
     * and "-I" (isolated mode) makes Python ignore PYTHON* variables and the current folder,
     * so nothing from the cloned repository can be imported by mistake.
     *
     * @param  list<string>  $paths
     * @return array{files: list<array{path: string, language: string|null, lines: int, symbols: list<array{kind: string, name: string, start_line: int, end_line: int}>, imports: list<array{raw: string, resolved_path: string|null, external: bool}>}>, errors: list<array{path: string, message: string}>}
     */
    private function runAnalyzer(Repository $repository, array $paths): array
    {
        $python = config('services.analyzer.python');

        if (! is_file($python)) {
            Log::error('The code analyzer is not installed. Run: composer analyzer:install', ['python' => $python]);

            throw new RepositoryProcessingException('Analizorul de cod nu este instalat pe server, așa că nu am putut analiza codul.');
        }

        try {
            $result = Process::timeout(self::TIMEOUT_SECONDS)
                ->input(implode("\n", $paths))
                ->run([$python, '-I', base_path('analyzer/analyze.py'), $repository->clonePath(), '--files-from', '-']);
        } catch (ProcessTimedOutException) {
            Log::warning('The code analyzer timed out.', [
                'repository_id' => $repository->id,
                'timeout_seconds' => self::TIMEOUT_SECONDS,
            ]);

            $minutes = intdiv(self::TIMEOUT_SECONDS, 60);

            throw new RepositoryProcessingException("Analiza codului a durat mai mult de {$minutes} minute, așa că am oprit-o. Repository-ul este probabil prea mare.");
        }

        $analysis = json_decode($result->output(), true);

        if ($result->failed() || ! is_array($analysis) || ! is_array($analysis['files'] ?? null)) {
            Log::error('The code analyzer failed.', [
                'repository_id' => $repository->id,
                'exit_code' => $result->exitCode(),
                'analyzer_output' => Str::limit($result->errorOutput(), 2000),
            ]);

            throw new RepositoryProcessingException('Nu am putut analiza codul repository-ului. Încearcă din nou.');
        }

        if (($analysis['errors'] ?? []) !== []) {
            Log::warning('Some files could not be analyzed.', [
                'repository_id' => $repository->id,
                'count' => count($analysis['errors']),
                'errors' => array_slice($analysis['errors'], 0, 20),
            ]);
        }

        return $analysis;
    }

    /**
     * Replace the repository's previous analysis with this one and return the number of modules.
     * It runs inside a transaction: the pages see either the old analysis or the new one, never half.
     *
     * @param  list<array{path: string, mode: string, blob_sha: string, size_bytes: int, is_binary: bool}>  $filesToAnalyze
     * @param  list<array{path: string, language: string|null, lines: int, symbols: list<array{kind: string, name: string, start_line: int, end_line: int}>, imports: list<array{raw: string, resolved_path: string|null, external: bool}>}>  $analyzedFiles
     */
    private function save(Repository $repository, array $filesToAnalyze, array $analyzedFiles): int
    {
        ModuleDependency::whereBelongsTo($repository)->delete();
        FileImport::whereBelongsTo($repository)->delete();
        CodeSymbol::whereBelongsTo($repository)->delete();
        RepositoryFile::whereBelongsTo($repository)->delete();
        Module::whereBelongsTo($repository)->delete();

        $moduleOfFile = ModuleGrouper::group(array_column($analyzedFiles, 'path'));

        $moduleIds = $this->saveModules($repository, $analyzedFiles, $moduleOfFile);
        $fileIds = $this->saveFiles($repository, $filesToAnalyze, $analyzedFiles, $moduleOfFile, $moduleIds);
        $this->saveSymbolsAndImports($repository, $analyzedFiles, $fileIds);
        $this->saveModuleDependencies($repository, $analyzedFiles, $moduleOfFile, $moduleIds);

        $repository->update([
            'analyzed_at' => now(),
            'description' => $this->readmeDescription($repository, array_column($analyzedFiles, 'path')),
        ]);

        return count($moduleIds);
    }

    /**
     * Save one row for each module, with its number of files and lines.
     *
     * @param  list<array{path: string, lines: int}>  $analyzedFiles
     * @param  array<string, string>  $moduleOfFile
     * @return array<string, int> module path => module id
     */
    private function saveModules(Repository $repository, array $analyzedFiles, array $moduleOfFile): array
    {
        $rows = collect($analyzedFiles)
            ->groupBy(fn (array $file): string => $moduleOfFile[$file['path']])
            ->map(fn (Collection $files, string|int $path): array => [
                'repository_id' => $repository->id,
                'path' => (string) $path,
                'name' => $path === ModuleGrouper::ROOT_MODULE ? $repository->name : (string) $path,
                'file_count' => $files->count(),
                'line_count' => $files->sum('lines'),
            ]);

        $this->insertInChunks(Module::class, $rows->values()->all());

        return $repository->modules()->pluck('id', 'path')->all();
    }

    /**
     * Save one row for each analyzed file, already linked to its module.
     *
     * @param  list<array{path: string, mode: string, blob_sha: string, size_bytes: int, is_binary: bool}>  $filesToAnalyze
     * @param  list<array{path: string, language: string|null, lines: int}>  $analyzedFiles
     * @param  array<string, string>  $moduleOfFile
     * @param  array<string, int>  $moduleIds
     * @return array<string, int> file path => file id
     */
    private function saveFiles(Repository $repository, array $filesToAnalyze, array $analyzedFiles, array $moduleOfFile, array $moduleIds): array
    {
        $gitInfo = array_column($filesToAnalyze, null, 'path');

        $rows = array_map(fn (array $file): array => [
            'repository_id' => $repository->id,
            'module_id' => $moduleIds[$moduleOfFile[$file['path']]],
            'path' => $file['path'],
            'language' => $file['language'],
            'lines' => $file['lines'],
            'size_bytes' => $gitInfo[$file['path']]['size_bytes'],
            'blob_sha' => $gitInfo[$file['path']]['blob_sha'],
        ], $analyzedFiles);

        $this->insertInChunks(RepositoryFile::class, $rows);

        return $repository->files()->pluck('id', 'path')->all();
    }

    /**
     * Save the symbols and the imports of every file. An import that points to a file
     * of the repository gets that file's id (target_file_id).
     *
     * @param  list<array{path: string, symbols: list<array{kind: string, name: string, start_line: int, end_line: int}>, imports: list<array{raw: string, resolved_path: string|null, external: bool}>}>  $analyzedFiles
     * @param  array<string, int>  $fileIds
     */
    private function saveSymbolsAndImports(Repository $repository, array $analyzedFiles, array $fileIds): void
    {
        $symbolRows = [];
        $importRows = [];

        foreach ($analyzedFiles as $file) {
            foreach ($file['symbols'] as $symbol) {
                $symbolRows[] = [
                    'repository_id' => $repository->id,
                    'repository_file_id' => $fileIds[$file['path']],
                    'kind' => mb_substr($symbol['kind'], 0, 20),
                    'name' => mb_substr($symbol['name'], 0, 255),
                    'start_line' => $symbol['start_line'],
                    'end_line' => $symbol['end_line'],
                ];
            }

            foreach ($file['imports'] as $import) {
                $importRows[] = [
                    'repository_id' => $repository->id,
                    'repository_file_id' => $fileIds[$file['path']],
                    'target' => mb_substr($import['raw'], 0, 1024),
                    'target_file_id' => $fileIds[$import['resolved_path'] ?? ''] ?? null,
                    'is_external' => $import['external'],
                ];
            }
        }

        $this->insertInChunks(CodeSymbol::class, $symbolRows);
        $this->insertInChunks(FileImport::class, $importRows);
    }

    /**
     * Save the dependency graph: module A depends on module B when a file of A imports a file of B.
     * The weight is the number of such imports. Imports inside the same module are not dependencies.
     *
     * @param  list<array{path: string, imports: list<array{raw: string, resolved_path: string|null, external: bool}>}>  $analyzedFiles
     * @param  array<string, string>  $moduleOfFile
     * @param  array<string, int>  $moduleIds
     */
    private function saveModuleDependencies(Repository $repository, array $analyzedFiles, array $moduleOfFile, array $moduleIds): void
    {
        $weights = [];

        foreach ($analyzedFiles as $file) {
            foreach ($file['imports'] as $import) {
                $fromModule = $moduleOfFile[$file['path']];
                $toModule = $moduleOfFile[$import['resolved_path'] ?? ''] ?? null;

                if ($toModule === null || $toModule === $fromModule) {
                    continue;
                }

                $weights[$fromModule][$toModule] = ($weights[$fromModule][$toModule] ?? 0) + 1;
            }
        }

        $rows = [];

        foreach ($weights as $fromModule => $targets) {
            foreach ($targets as $toModule => $weight) {
                $rows[] = [
                    'repository_id' => $repository->id,
                    'from_module_id' => $moduleIds[$fromModule],
                    'to_module_id' => $moduleIds[$toModule],
                    'weight' => $weight,
                ];
            }
        }

        $this->insertInChunks(ModuleDependency::class, $rows);
    }

    /**
     * The first paragraph of the README in the root folder, if there is one (see ReadmeDescription).
     *
     * @param  list<string>  $paths
     */
    private function readmeDescription(Repository $repository, array $paths): ?string
    {
        $readme = collect($paths)->first(
            fn (string $path): bool => preg_match('/\Areadme(\.md|\.markdown|\.txt)?\z/i', $path) === 1,
        );

        if ($readme === null) {
            return null;
        }

        return ReadmeDescription::fromMarkdown(File::get($repository->clonePath().'/'.$readme));
    }

    /**
     * Insert many rows with a few big INSERT queries instead of one query per row.
     *
     * @param  class-string<Model>  $model
     * @param  list<array<string, mixed>>  $rows
     */
    private function insertInChunks(string $model, array $rows): void
    {
        foreach (array_chunk($rows, self::INSERT_CHUNK_SIZE) as $chunk) {
            $model::insert($chunk);
        }
    }
}
